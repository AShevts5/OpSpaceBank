export function localAnswer(question: string): string {
  const q = question.toLowerCase()
  let best: [number, string] | null = null
  for (const [keys, answer] of FAQ) {
    const score = keys.filter((k) => q.includes(k)).length
    if (score && (!best || score > best[0])) best = [score, answer]
  }
  return (
    best?.[1] ??
    'Сейчас я работаю в автономном режиме, поэтому отвечаю только по темам приложения: три задачи, СДНФ/СКНФ, метод Квайна, законы де Моргана, приоритет операций, Process Mining, 2FA и офлайн-режим. Подключитесь к сети и войдите в аккаунт — тогда отвечу на любые вопросы.'
  )
}

