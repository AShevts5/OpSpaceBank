def local_answer(question: str) -> str:
    q = question.lower()
    q = re.sub(r"\s+", " ", q)
    scored = []
    for keys, answer in FAQ:
        score = sum(1 for k in keys if k in q)
        if score:
            scored.append((score, answer))
    if scored:
        scored.sort(key=lambda s: -s[0])
        return scored[0][1]
    return (
        "Сейчас я работаю в автономном режиме (без языковой модели), поэтому отвечаю только по темам приложения: "
        "три задачи, СДНФ/СКНФ, метод Квайна, законы де Моргана, приоритет операций, Process Mining, 2FA и офлайн-режим. "
        "Попробуйте переформулировать вопрос."
    )
